import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {existsSync} from 'node:fs';
const executablePath=process.env.CHROMIUM_PATH || (existsSync('/usr/bin/chromium')?'/usr/bin/chromium':undefined);
const browser=await chromium.launch({executablePath,headless:true});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const response=await page.request.get('http://127.0.0.1:5500/projects/demo.json');
 assert.equal(response.status(),200);
 assert.equal((await response.json()).elements[1].content,'سلام از فایل JSON');
 await page.goto('http://127.0.0.1:5500/');
 await page.waitForFunction(()=>Boolean(window.studio?.timeline));
 assert.equal(await page.locator('[data-element-id="title"]').textContent(),'سلام از فایل JSON');
 assert.equal(await page.evaluate(()=>studio.timeline.duration()),10);
 assert.equal(await page.locator('[data-element-id="title"]').evaluate(e=>getComputedStyle(e).opacity),'0');
 await page.click('#play');
 await page.waitForFunction(()=>studio.timeline.time()>0.2);
 await page.click('#pause');
 assert.equal(await page.evaluate(()=>studio.timeline.paused()),true);
 await page.locator('#seek').evaluate(e=>{e.value='5';e.dispatchEvent(new Event('input'));});
 assert.equal(await page.evaluate(()=>studio.timeline.time()),5);
 const snapshot=()=>page.locator('[data-element-id="orb"]').evaluate(e=>e.style.transform);
 const first=await snapshot();
 await page.locator('#seek').evaluate(e=>{e.value='8';e.dispatchEvent(new Event('input'));e.value='5';e.dispatchEvent(new Event('input'));});
 assert.equal(await snapshot(),first);
 assert.equal(await page.locator('[data-element-id="title"]').evaluate(e=>getComputedStyle(e).opacity),'1');
 await page.screenshot({path:'test-results/studio.png'});
 await page.click('#restart');
 await page.waitForFunction(()=>studio.timeline.time()<1 && !studio.timeline.paused());
 await page.click('#pause');
 await page.route('**/projects/demo.json',async route=>{const p=await response.json();p.elements[1].content='متن جدید از JSON';await route.fulfill({json:p});});
 await page.click('#reload');
 await page.waitForFunction(()=>document.querySelector('[data-element-id="title"]')?.textContent==='متن جدید از JSON');
 await page.route('**/projects/demo.json',route=>route.fulfill({status:422,body:'Invalid project'}));
 await page.click('#reload');
 await page.waitForFunction(()=>document.getElementById('status').textContent.includes('HTTP 422'));
 assert.equal(await page.locator('#play').isDisabled(),true);
 await page.unroute('**/projects/demo.json');
 await page.click('#reload');
 await page.waitForFunction(()=>!document.getElementById('play').disabled);
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 assert.deepEqual(errors,[]);
 console.log('PASS: JSON fetch, scene, initial state, play, pause, seek, repeatable seek, restart, JSON reload, failure recovery, mobile layout; no browser exceptions');
} finally {await browser.close();}
